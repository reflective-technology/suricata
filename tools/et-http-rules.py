#!/usr/bin/env python3
"""Build configs/rules/et-http.rules from an ET Open (suricata-8.0) rules directory.

The sensor parses only HTTP / HTTP2, so a rule for any other protocol fails to load.
This keeps the enabled `alert http` and `alert http1` rules of the chosen categories, drops the sids in
DISABLED, and keeps ET's license header.

  curl -sSfO https://rules.emergingthreats.net/open/suricata-8.0/emerging.rules.tar.gz
  tar -xzf emerging.rules.tar.gz
  curl -sSf https://rules.emergingthreats.net/open/suricata-8.0/version.txt   # e.g. 11313
  tools/et-http-rules.py rules <version> > configs/rules/et-http.rules
"""
import re
import sys
from pathlib import Path

CATEGORIES = ["attack_response", "web_server", "exploit", "web_specific_apps"]
# Generic rules that fire on ordinary traffic.
DISABLED = {
    2101603: "GPL WEB_SERVER DELETE attempt: any DELETE request, e.g. REST APIs",
}


def main(rules_dir, version):
    rules_dir = Path(rules_dir)
    license_text = (rules_dir / "LICENSE").read_text()
    out = [license_text.rstrip("\n"), "#",
           f"# ET Open suricata-8.0 version {version}: enabled `alert http` and `alert http1` rules of",
           f"# {', '.join(CATEGORIES)}.",
           "# Generated by tools/et-http-rules.py; do not edit by hand.",
           "# Disabled:"]
    out += [f"#   {sid} {why}" for sid, why in sorted(DISABLED.items())]
    kept = 0
    for cat in CATEGORIES:
        out.append(f"\n# emerging-{cat}.rules")
        for line in (rules_dir / f"emerging-{cat}.rules").read_text().splitlines():
            if not line.startswith(("alert http ", "alert http1 ")):
                continue
            sid = int(re.search(r"\bsid:(\d+);", line).group(1))
            if sid in DISABLED:
                continue
            out.append(line)
            kept += 1
    print("\n".join(out))
    print(f"{kept} rules", file=sys.stderr)


if __name__ == "__main__":
    main(*sys.argv[1:3])
